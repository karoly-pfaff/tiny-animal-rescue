import { access, readFile } from 'node:fs/promises';
import path from 'node:path';
import { listRepositoryFiles, repositoryPath } from './lib/repository-files.mjs';
import { isWatermarkPolicyExemption, validateWatermarkRecord } from './lib/watermark-policy.mjs';

const textExtensions = new Set([
  '.css',
  '.html',
  '.js',
  '.json',
  '.jsx',
  '.md',
  '.mjs',
  '.svg',
  '.ts',
  '.tsx',
  '.txt',
  '.yaml',
  '.yml',
]);
const mediaExtensions = new Set([
  '.aac',
  '.flac',
  '.jpeg',
  '.jpg',
  '.mp3',
  '.ogg',
  '.png',
  '.wav',
  '.webp',
]);
const authorshipExample = ['written', 'by', 'AI'].join(' ');
const normativeExample =
  `Forbidden examples include “generated by”, “created with”, “${authorshipExample}”, agent/editor/tool badges,\n` +
  'bot signatures, model names used as attribution, promotional links, injected logos, audible tags,\n' +
  'visual watermarks, and fabricated `Co-authored-by`, `Reviewed-by`, or similar trailers.';

function contentForScan(relative, content) {
  if (relative !== 'docs/delivery/story-commit-workflow.md') return content;
  return content.replace(
    normativeExample,
    normativeExample.replace(authorshipExample, 'authorship phrase'),
  );
}
const files = await listRepositoryFiles();
try {
  await access('build');
  files.push(
    ...(await listRepositoryFiles('build')).filter(
      (file) => !repositoryPath(file).startsWith('build/reports/'),
    ),
  );
} catch {
  // A source-only story gate may run before the production build exists.
}
const findings = [];
let inspected = 0;

for (const file of files) {
  const relative = repositoryPath(file);
  if (isWatermarkPolicyExemption(relative)) continue;
  const extension = path.extname(file).toLowerCase();
  if (textExtensions.has(extension)) {
    const content = contentForScan(relative, await readFile(file, 'utf8'));
    findings.push(...validateWatermarkRecord({ channel: 'text', path: relative, content }));
    if (extension === '.json') {
      try {
        findings.push(
          ...validateWatermarkRecord({
            channel: 'metadata',
            path: relative,
            content,
            metadata: JSON.parse(content),
          }),
        );
      } catch {
        // Syntax validity belongs to the owning JSON/schema gate.
      }
    }
    inspected += 1;
  } else if (mediaExtensions.has(extension)) {
    const content = (await readFile(file)).toString('latin1');
    findings.push(...validateWatermarkRecord({ channel: 'binary', path: relative, content }));
    inspected += 1;
  }
}

if (inspected === 0) findings.push('Watermark scan found no eligible authored file.');
if (findings.length > 0) {
  console.error(findings.join('\n'));
  process.exit(1);
}
console.log(`Watermark scan inspected ${inspected} authored text/media file(s).`);
