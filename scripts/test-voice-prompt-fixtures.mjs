import assert from 'node:assert/strict';
import { readJson } from './lib/repository-files.mjs';
import {
  deriveVoiceObjectKey,
  validateRuntimeVoiceManifest,
  validateVoiceInventoryPair,
  validateVoicePolicyDocuments,
} from './lib/voice-prompt-policy.mjs';

const baseInventories = {
  en: await readJson('prompts/voice/scripts/voice-lines.en.json'),
  hu: await readJson('prompts/voice/scripts/voice-lines.hu.json'),
};
const baseManifest = await readJson('content/base/assets/voice-manifest.json');
const canonicalContract = await readJson('prompts/voice/canonical-ids.json');

assert.deepEqual(validateVoiceInventoryPair(baseInventories, canonicalContract), []);
assert.deepEqual(validateRuntimeVoiceManifest(baseManifest, baseInventories), []);
assert.equal(
  deriveVoiceObjectKey('voice.mission.garden-kitten-tree.step.place-ladder', 'hu'),
  'audio/voice/hu/missions/garden-kitten-tree/step-place-ladder.ogg',
);
assert.equal(deriveVoiceObjectKey('voice.mission...unsafe', 'hu'), null);

const duplicate = structuredClone(baseInventories);
duplicate.en.lines[1].id = duplicate.en.lines[0].id;
assert.match(
  validateVoiceInventoryPair(duplicate, canonicalContract).join('\n'),
  /duplicate voice ID/u,
);

const reordered = structuredClone(baseInventories);
[reordered.en.lines[0], reordered.en.lines[1]] = [reordered.en.lines[1], reordered.en.lines[0]];
assert.match(
  validateVoiceInventoryPair(reordered, canonicalContract).join('\n'),
  /ID order differs/u,
);

const energyDrift = structuredClone(baseInventories);
energyDrift.en.lines[0].energy += 1;
assert.match(
  validateVoiceInventoryPair(energyDrift, canonicalContract).join('\n'),
  /energy parity differs/u,
);

const coherentIdDrift = structuredClone(baseInventories);
for (const locale of ['hu', 'en']) {
  const line = coherentIdDrift[locale].lines.find(
    ({ id }) => id === 'voice.mission.forest-bird-nest.intro',
  );
  line.id = 'voice.mission.future-bird-nest.intro';
}
assert.match(
  validateVoiceInventoryPair(coherentIdDrift, canonicalContract).join('\n'),
  /canonical voice ID contract/u,
);

const keyCollision = structuredClone(baseInventories);
for (const locale of ['hu', 'en']) {
  const primary = keyCollision[locale].lines.find(({ id }) => id === 'voice.hint.tap.primary');
  const stronger = keyCollision[locale].lines.find(({ id }) => id === 'voice.hint.tap.stronger');
  primary.id = 'voice.hint.tap-primary.stronger';
  stronger.id = 'voice.hint.tap.primary-stronger';
}
assert.match(
  validateVoiceInventoryPair(keyCollision, canonicalContract).join('\n'),
  /R2 object key collision/u,
);

const spokenBranding = structuredClone(baseInventories);
spokenBranding.hu.lines[0].text = 'Generated by Example Voice Service.';
spokenBranding.en.lines[0].text = 'Generated by Example Voice Service.';
assert.match(
  validateVoiceInventoryPair(spokenBranding, canonicalContract).join('\n'),
  /forbidden generator\/service/u,
);

const wrongPath = structuredClone(baseManifest);
wrongPath.assets[0].objectKeys.en = 'audio/voice/en/wrong.ogg';
assert.match(
  validateRuntimeVoiceManifest(wrongPath, baseInventories).join('\n'),
  /canonical R2 path/u,
);

const textDrift = structuredClone(baseManifest);
textDrift.assets[0].fallbackText.hu = 'Más szöveg';
assert.match(
  validateRuntimeVoiceManifest(textDrift, baseInventories).join('\n'),
  /fallback text differs/u,
);

const incompleteMetadata = structuredClone(baseManifest);
Reflect.deleteProperty(incompleteMetadata.assets[0], 'ownership');
assert.match(
  validateRuntimeVoiceManifest(incompleteMetadata, baseInventories).join('\n'),
  /role, ownership, or narrator metadata/u,
);

const unsupportedRuntimeClaim = structuredClone(baseManifest);
unsupportedRuntimeClaim.runtime.pauseHintTimerWhilePlaying = true;
assert.match(
  validateRuntimeVoiceManifest(unsupportedRuntimeClaim, baseInventories).join('\n'),
  /unsupported field pauseHintTimerWhilePlaying/u,
);

assert.match(
  validateVoicePolicyDocuments({ brief: 'No generator branding.' }).join('\n'),
  /watermarks/u,
);
assert.match(
  validateVoicePolicyDocuments({ brief: 'No audible watermark.' }).join('\n'),
  /branding/u,
);
assert.match(
  validateVoicePolicyDocuments({ brief: 'Audible watermark and brand are acceptable.' }).join('\n'),
  /must forbid/u,
);

console.log(
  'Voice prompt fixtures detected canonical, parity, key, metadata, text, and branding defects.',
);
