const firstRescueVoiceCues = Object.freeze([
  'voice.mission.garden-kitten-tree.step.place-ladder',
  'voice.mission.garden-kitten-tree.step.help-mimi-down',
  'voice.mission.garden-kitten-tree.success',
]);

const locales = Object.freeze(['hu', 'en']);
const inventoryPaths = Object.freeze({
  en: 'prompts/voice/scripts/voice-lines.en.json',
  hu: 'prompts/voice/scripts/voice-lines.hu.json',
});
const expectedGroupCounts = Object.freeze({
  global: 12,
  hint: 10,
  location: 7,
  'mission-intro': 16,
  'mission-step': 38,
  'mission-success': 16,
  parent: 4,
  resident: 12,
});
const safeObjectKey = /^[a-z0-9][a-z0-9./-]+\.ogg$/u;
const forbiddenSpokenOutput =
  /(?:generated by|powered by|voice service|generator|watermark|promotional (?:message|tag)|openai|elevenlabs|suno|udio|https?:\/\/|www\.)/iu;

function semanticMetadata(id) {
  const simplePatterns = [
    [/^voice\.global\.([a-z0-9-]+)$/u, 'global', (match) => `global/${match[1]}.ogg`],
    [
      /^voice\.location\.([a-z0-9-]+)\.name$/u,
      'location',
      (match) => `locations/${match[1]}-name.ogg`,
    ],
    [
      /^voice\.shelter\.([a-z0-9-]+)\.name$/u,
      'location',
      (match) => `shelter/${match[1]}-name.ogg`,
    ],
    [
      /^voice\.hint\.([a-z0-9-]+)\.([a-z0-9-]+)$/u,
      'hint',
      (match) => `hints/${match[1]}-${match[2]}.ogg`,
    ],
    [
      /^voice\.resident\.([a-z0-9-]+)\.name$/u,
      'resident',
      (match) => `residents/${match[1]}-name.ogg`,
    ],
    [/^voice\.parent\.([a-z0-9-]+)$/u, 'parent', (match) => `parent/${match[1]}.ogg`],
  ];

  for (const [pattern, group, pathFor] of simplePatterns) {
    const match = id.match(pattern);
    if (match !== null) return { group, relativePath: pathFor(match) };
  }

  const mission = id.match(/^voice\.mission\.([a-z0-9-]+)\.(intro|success|step\.([a-z0-9-]+))$/u);
  if (mission === null) return null;
  if (mission[2] === 'intro') {
    return { group: 'mission-intro', relativePath: `missions/${mission[1]}/intro.ogg` };
  }
  if (mission[2] === 'success') {
    return { group: 'mission-success', relativePath: `missions/${mission[1]}/success.ogg` };
  }
  return {
    group: 'mission-step',
    relativePath: `missions/${mission[1]}/step-${mission[3]}.ogg`,
  };
}

export function deriveVoiceObjectKey(id, locale) {
  if (!locales.includes(locale)) return null;
  const metadata = semanticMetadata(id);
  return metadata === null ? null : `audio/voice/${locale}/${metadata.relativePath}`;
}

function expandCanonicalVoiceIds(contract) {
  const global = contract.global.map((id) => ({ group: 'global', id: `voice.global.${id}` }));
  const locations = contract.locations.map((id) => ({
    group: 'location',
    id: `voice.location.${id}.name`,
  }));
  const shelter = contract.shelterAreas.map((id) => ({
    group: 'location',
    id: `voice.shelter.${id}.name`,
  }));
  const hints = contract.hints.flatMap(({ interaction, levels }) =>
    levels.map((level) => ({ group: 'hint', id: `voice.hint.${interaction}.${level}` })),
  );
  const residents = contract.residents.map((id) => ({
    group: 'resident',
    id: `voice.resident.${id}.name`,
  }));
  const parent = contract.parent.map((id) => ({ group: 'parent', id: `voice.parent.${id}` }));
  const missions = contract.missions.flatMap(({ id, steps }) => [
    { group: 'mission-intro', id: `voice.mission.${id}.intro` },
    ...steps.map((step) => ({ group: 'mission-step', id: `voice.mission.${id}.step.${step}` })),
    { group: 'mission-success', id: `voice.mission.${id}.success` },
  ]);
  return [...global, ...locations, ...shelter, ...hints, ...residents, ...parent, ...missions];
}

function validateSpokenText(line, locale) {
  return forbiddenSpokenOutput.test(line.text)
    ? [`${locale}: ${line.id} contains forbidden generator/service or promotional speech.`]
    : [];
}

function validateCanonicalLine(line, canonicalLine, locale, index) {
  if (line.id !== canonicalLine?.id || line.group !== canonicalLine?.group) {
    return [`${locale}: line ${String(index + 1)} differs from the canonical voice ID contract.`];
  }
  return [];
}

function validateLocaleInventory(inventory, locale, canonicalLines) {
  const findings = [];
  if (inventory.locale !== locale) findings.push(`${locale}: locale field must match the file.`);
  if (inventory.lines.length !== 115) findings.push(`${locale}: inventory must contain 115 lines.`);

  const seen = new Set();
  const objectKeys = new Set();
  for (const [index, line] of inventory.lines.entries()) {
    if (seen.has(line.id)) findings.push(`${locale}: duplicate voice ID ${line.id}.`);
    seen.add(line.id);
    const metadata = semanticMetadata(line.id);
    if (metadata === null) {
      findings.push(`${locale}: unsupported voice ID structure ${line.id}.`);
    } else if (metadata.group !== line.group) {
      findings.push(`${locale}: ${line.id} must use group ${metadata.group}.`);
    }
    const objectKey = deriveVoiceObjectKey(line.id, locale);
    if (objectKey !== null && objectKeys.has(objectKey)) {
      findings.push(`${locale}: R2 object key collision at ${objectKey}.`);
    }
    if (objectKey !== null) objectKeys.add(objectKey);
    findings.push(...validateSpokenText(line, locale));
    findings.push(...validateCanonicalLine(line, canonicalLines[index], locale, index));
  }

  for (const [group, count] of Object.entries(expectedGroupCounts)) {
    const actual = inventory.lines.filter((line) => line.group === group).length;
    if (actual !== count) findings.push(`${locale}: ${group} must contain ${String(count)} lines.`);
  }
  return findings;
}

function validateLocaleParity(hu, en) {
  const findings = [];
  const count = Math.max(hu.lines.length, en.lines.length);
  for (let index = 0; index < count; index += 1) {
    const huLine = hu.lines[index];
    const enLine = en.lines[index];
    if (huLine?.id !== enLine?.id) {
      findings.push(`HU/EN ID order differs at line ${String(index + 1)}.`);
      continue;
    }
    if (huLine?.group !== enLine?.group) findings.push(`${huLine.id}: group parity differs.`);
    if (huLine?.energy !== enLine?.energy) findings.push(`${huLine.id}: energy parity differs.`);
  }
  return findings;
}

export function validateVoiceInventoryPair(inventories, canonicalContract) {
  const canonicalLines = expandCanonicalVoiceIds(canonicalContract);
  const contractFindings =
    canonicalContract.version === 1 && canonicalLines.length === 115
      ? []
      : ['Canonical voice ID contract must be version 1 with exactly 115 lines.'];
  return [
    ...contractFindings,
    ...validateLocaleInventory(inventories.hu, 'hu', canonicalLines),
    ...validateLocaleInventory(inventories.en, 'en', canonicalLines),
    ...validateLocaleParity(inventories.hu, inventories.en),
  ];
}

function validateRuntimePolicy(runtime) {
  const expected = {
    maxConcurrentVoices: 1,
    replaceCurrentOnNewLine: true,
  };
  const findings = Object.entries(expected)
    .filter(([field, value]) => runtime?.[field] !== value)
    .map(([field]) => `Voice runtime policy has an invalid ${field} value.`);
  for (const field of Object.keys(runtime ?? {})) {
    if (!Object.hasOwn(expected, field)) {
      findings.push(`Voice runtime policy declares unsupported field ${field}.`);
    }
  }
  return findings;
}

function lineMap(inventory) {
  return new Map(inventory.lines.map((line) => [line.id, line]));
}

function validateRuntimeAssetLocale(asset, lines, locale) {
  const findings = [];
  const line = lines.get(asset.cue);
  const expectedKey = deriveVoiceObjectKey(asset.cue, locale);
  const actualKey = asset.objectKeys?.[locale];
  if (line === undefined) findings.push(`${asset.cue}: missing ${locale} prompt inventory line.`);
  if (asset.fallbackText?.[locale] !== line?.text) {
    findings.push(`${asset.cue}: ${locale} fallback text differs from the prompt inventory.`);
  }
  if (
    actualKey !== expectedKey ||
    !safeObjectKey.test(actualKey ?? '') ||
    actualKey.includes('..')
  ) {
    findings.push(`${asset.cue}: ${locale} object key does not match the canonical R2 path.`);
  }
  if (asset.promptInventories?.[locale] !== inventoryPaths[locale]) {
    findings.push(`${asset.cue}: ${locale} prompt inventory path is not authoritative.`);
  }
  return findings;
}

function validateRuntimeAssetProductionMetadata(asset) {
  const findings = [];
  const expectedRole = asset.cue.endsWith('.success') ? 'mission-success' : 'required-instruction';
  const expectedIdentity = {
    narratorRole: 'primary',
    ownership: 'base',
    role: expectedRole,
  };
  if (Object.entries(expectedIdentity).some(([field, value]) => asset[field] !== value)) {
    findings.push(`${asset.cue}: role, ownership, or narrator metadata is invalid.`);
  }
  const expectedStatus = {
    licenseStatus: 'pending-production',
    provenanceStatus: 'pending-production',
  };
  if (Object.entries(expectedStatus).some(([field, value]) => asset[field] !== value)) {
    findings.push(`${asset.cue}: license and provenance must remain pending until production.`);
  }
  findings.push(...validateDurationBounds(asset));
  return findings;
}

function validateDurationBounds(asset) {
  const bounds = asset.durationBoundsSeconds;
  const numeric = typeof bounds?.min === 'number' && typeof bounds?.max === 'number';
  const invalidRange =
    numeric && [bounds.min <= 0, bounds.max > 2.5, bounds.min >= bounds.max].some(Boolean);
  return numeric && !invalidRange
    ? []
    : [`${asset.cue}: narration duration bounds must be positive and at most 2.5 seconds.`];
}

function validateRuntimeAsset(asset, linesByLocale) {
  const findings = [];
  if (asset.promptQaStatus !== 'approved') {
    findings.push(`${asset.cue}: prompt QA must be approved.`);
  }
  if (asset.audioQaStatus !== 'not-produced') {
    findings.push(`${asset.cue}: pending R2 audio must remain explicitly not-produced.`);
  }
  findings.push(...validateRuntimeAssetProductionMetadata(asset));
  for (const locale of locales) {
    findings.push(...validateRuntimeAssetLocale(asset, linesByLocale[locale], locale));
  }
  return findings;
}

export function validateRuntimeVoiceManifest(manifest, inventories) {
  const findings = [];
  if (
    manifest.schemaVersion !== 1 ||
    manifest.category !== 'voice' ||
    manifest.format !== 'ogg' ||
    manifest.locales?.join(',') !== 'hu,en'
  ) {
    findings.push('Runtime voice manifest identity is invalid.');
  }
  if (manifest.delivery !== 'r2-pending') {
    findings.push('Runtime voice manifest delivery must remain r2-pending until audio QA exists.');
  }
  findings.push(...validateRuntimePolicy(manifest.runtime));
  const assets = Array.isArray(manifest.assets) ? manifest.assets : [];
  const cues = assets.map((asset) => asset.cue);
  if (new Set(cues).size !== cues.length)
    findings.push('Runtime voice manifest contains duplicate cues.');
  if (
    cues.length !== firstRescueVoiceCues.length ||
    firstRescueVoiceCues.some((cue) => !cues.includes(cue))
  ) {
    findings.push('Runtime voice manifest must contain exactly the first-rescue required cues.');
  }
  const linesByLocale = { en: lineMap(inventories.en), hu: lineMap(inventories.hu) };
  for (const asset of assets) findings.push(...validateRuntimeAsset(asset, linesByLocale));
  return findings;
}

export function validateVoicePolicyDocuments(documents) {
  return Object.entries(documents).flatMap(([name, content]) => {
    const findings = [];
    const prohibition = '(?:no|not|never|forbid|prohibit|reject|without|may not|must not|do not)';
    const normalizedContent = content.replace(/\s+/gu, ' ');
    if (!new RegExp(`${prohibition}.{0,240}watermark`, 'iu').test(normalizedContent)) {
      findings.push(`${name} must forbid audible watermarks.`);
    }
    if (
      !new RegExp(`${prohibition}.{0,240}(?:branding|brand|generator tag|service name)`, 'iu').test(
        normalizedContent,
      )
    ) {
      findings.push(`${name} must forbid audible generator or service branding.`);
    }
    return findings;
  });
}
